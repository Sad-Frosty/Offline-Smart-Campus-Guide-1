List<CampusBuilding> searchBuildings(String query) {
  final lowerQuery = query.toLowerCase();
  return campusBuildings.where((building) {
    return building.name.toLowerCase().contains(lowerQuery) ||
        building.description.toLowerCase().contains(lowerQuery) ||
        building.category.toLowerCase().contains(lowerQuery);
  }).toList();
}
